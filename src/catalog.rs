#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AttentionKind {
    MlaCompressedKv,
    GroupedQueryAttention,
    HybridDeltaNetGqa,
    HybridMamba3Swa,
    DiffusionDiT,
    BidirectionalEncoder,
}

impl AttentionKind {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::MlaCompressedKv => "MLA (57x Compressed Latent KV)",
            Self::GroupedQueryAttention => "GQA (Grouped-Query Attention)",
            Self::HybridDeltaNetGqa => "Hybrid Gated-DeltaNet + GQA",
            Self::HybridMamba3Swa => "Hybrid Mamba-3 + Sliding-Window Attention",
            Self::DiffusionDiT => "Flow-Matching Diffusion Transformer (DiT)",
            Self::BidirectionalEncoder => "System One Calibrated Decision Encoder",
        }
    }
}

