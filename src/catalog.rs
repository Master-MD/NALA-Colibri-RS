pub fn find_model(query: &str) -> Option<&'static CatalogModel> {
    let q = query.trim().to_ascii_lowercase();
    if let Some(exact) = CATALOG_MODELS.iter().find(|m| m.slug == q) {
        return Some(exact);
    }
    CATALOG_MODELS.iter().find(|m| {
        m.slug.contains(&q)
            || m.display_name.to_ascii_lowercase().contains(&q)
            || m.family_id.eq_ignore_ascii_case(&q)
    })
}

pub fn find_family(id: &str) -> Option<&'static EngineFamily> {
    ENGINE_FAMILIES.iter().find(|f| f.id.eq_ignore_ascii_case(id))
}
